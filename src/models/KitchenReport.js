const mongoose = require('mongoose');
const timestamps = require('./timestamps');

/**
 * A kitchen's report for one closed period (a day, a week, a month or a
 * year), generated automatically when the period ends and kept as it was, so
 * past reports never change when data is edited later. Reports for the
 * current, still open period are worked out live instead (reportService).
 */
const kitchenReportSchema = new mongoose.Schema(
  {
    vendor_id: { type: mongoose.Schema.Types.ObjectId, ref: 'Vendor', required: true },
    period: { type: String, enum: ['daily', 'weekly', 'monthly', 'yearly'], required: true },
    start: { type: Date, required: true },
    end: { type: Date, required: true },
    label: { type: String, required: true },
    data: { type: mongoose.Schema.Types.Mixed, required: true },
    generated_at: { type: Date, default: Date.now },
    // 'schedule' (automatic at the end of the period) or 'manual' (regenerated by the kitchen).
    generated_by: { type: String, enum: ['schedule', 'manual'], default: 'schedule' },
  },
  { timestamps }
);

kitchenReportSchema.index({ vendor_id: 1, period: 1, start: 1 }, { unique: true });
kitchenReportSchema.index({ vendor_id: 1, period: 1, start: -1 });

module.exports = mongoose.model('KitchenReport', kitchenReportSchema);
